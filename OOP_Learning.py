class Animal:
    def __init__(self, name, age):
        self.name = name
        self.age = age
        def introduce(self):
            print(f"I\'m {name}, and I\'m {age} years old")
class Dog(Animal):
    def speak():
        print("Woof")
class Cat(Animal):
    def speak():
        print("Meow")
dog = Dog()
cat = Cat()
dog.introduce()
dog.speak()
cat.introduce()
cat.speak()